#!/usr/bin/env bash
# mojavez-v3 — deploy/docker/generate-secrets.sh
#
# Phase 25 (v1.9.7) — pays D-6-5. Generate random secrets for the
# docker-compose .env file. Uses openssl rand -hex 32 for each secret
# and prints a complete .env file to stdout (with empty SMS_* values
# that the admin fills in later for the SMS gateway).
#
# Usage:
#   bash deploy/docker/generate-secrets.sh > deploy/docker/.env
#
# Or to inspect the output before writing:
#   bash deploy/docker/generate-secrets.sh | less
#
# Do NOT commit deploy/docker/.env — add it to .gitignore (it already
# is, per .gitignore).
#
# Re-runnable: each invocation produces a fresh .env with new random
# secrets. Idempotent only in the sense that running it twice gives
# you two valid .env files (with different secrets).
set -e

CRON_SECRET=$(openssl rand -hex 32)
SYNC_SECRET=$(openssl rand -hex 32)
GATEWAY_API_KEY=$(openssl rand -hex 32)
DB_PASS=$(openssl rand -hex 16)
DB_ROOT_PASSWORD=$(openssl rand -hex 16)
SMS_API_KEY=""
SMS_SENDER=""

cat <<EOF
# Generated by deploy/docker/generate-secrets.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
# Do NOT commit this file. Add deploy/docker/.env to .gitignore.
# Re-run the script to regenerate (each run produces fresh secrets).

# --- Database ---
DB_ROOT_PASSWORD=${DB_ROOT_PASSWORD}
DB_NAME=mojavez_v3
DB_USER=mojavez
DB_PASSWORD=${DB_PASS}

# --- App ---
APP_ENV=production
INIT_DB=1

# Exposed port for the nginx 'web' service (host side).
MOJAVEZ_PORT=8080

# --- Secrets (random 32-byte hex) ---
CRON_SECRET=${CRON_SECRET}
SYNC_SECRET=${SYNC_SECRET}
GATEWAY_API_KEY=${GATEWAY_API_KEY}

# --- Initial admin ---
ADMIN_USERNAME=admin
# Override ADMIN_PASSWORD on first boot if you want a specific value.
# Leaving it empty makes the entrypoint generate a random one.
ADMIN_PASSWORD=

# --- Upstream national gateway ---
# Leave blank to use defaults (qr.mojavez.ir). Only set if you need to
# point at a mirror or staging instance.
NATIONAL_GATEWAY_BASE_URL=

# --- SMS gateway (Kavenegar-compatible) ---
# Leave blank in non-production (the app falls back to log-only mode).
SMS_API_KEY=${SMS_API_KEY}
SMS_SENDER=${SMS_SENDER}
EOF

echo "Generated secrets to stdout. Run: bash deploy/docker/generate-secrets.sh > deploy/docker/.env" >&2
